# Datetime helpers
# ===========================================================================

_GERRIT_TS_FORMATS: list[str] = [
    "%Y-%m-%d %H:%M:%S.%f000",
    "%Y-%m-%d %H:%M:%S.%f",
    "%Y-%m-%d %H:%M:%S",
]


def parse_gerrit_ts(ts: str | None) -> datetime | None:
    if not ts:
        return None
    ts_norm = re.sub(r"(\.\d{6})\d+", r"\1", ts)
    for fmt in _GERRIT_TS_FORMATS:
        try:
            return datetime.strptime(ts_norm, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def hours_between(start: datetime | None, end: datetime | None) -> float | None:
    if start is None or end is None:
        return None
    return (end - start).total_seconds() / 3600.0


def safe_mean(values: Iterable[float]) -> float | None:
    seq = [v for v in values if v is not None]
    return statistics.mean(seq) if seq else None


def safe_max(values: Iterable[float]) -> float | None:
    seq = [v for v in values if v is not None]
    return max(seq) if seq else None


