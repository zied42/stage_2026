def load_checkpoint(path: Path) -> dict[str, dict[str, Any]]:
    """Charge le checkpoint existant, migre l'ancien format si besoin."""
    if not path.exists():
        return {}
    try:
        with path.open("r", encoding="utf-8") as fh:
            raw = json.load(fh)
    except (json.JSONDecodeError, OSError) as exc:
        print(f"[WARN] Checkpoint illisible ({exc}) — on repart de zéro pour ce fichier.")
        return {}

    migrated: dict[str, dict[str, Any]] = {}
    for topic, value in raw.items():
        if isinstance(value, list):
            # ancien format : topic -> liste de changes brute
            migrated[topic] = {
                "changes": value,
                "done": True,
                "next_start": len(value),
            }
        elif isinstance(value, dict):
            migrated[topic] = {
                "changes": value.get("changes", []),
                "done": bool(value.get("done", False)),
                "next_start": value.get("next_start", len(value.get("changes", []))),
            }
    return migrated


def save_checkpoint(path: Path, data: dict[str, dict[str, Any]]) -> None:
    """Écriture atomique : fichier temporaire puis remplacement.
    Évite un fichier corrompu si le courant/le réseau coupe pendant l'écriture."""
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    with tmp_path.open("w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.flush()
        os.fsync(fh.fileno())
    tmp_path.replace(path)  # opération atomique sur la plupart des OS


