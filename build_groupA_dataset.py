"""
build_groupA_dataset.py
=======================
Self-contained pipeline for Group A blueprints — AVEC CHECKPOINT GRANULAIRE.

Steps
-----
1.  Read ``group_a_union.json`` (Launchpad blueprints + Gerrit topic URLs).
2.  Convert each topic URL → Gerrit REST API query.
3.  Download every change belonging to that topic (paginated, with retries).
4.  Aggregate topic-level features (identical logic to build_topic_dataset.py).
5.  Merge the Launchpad metadata (from group_a_union.json) with the Gerrit
    topic features.
6.  Write:
      • groupA_gerrit_raw.json        – raw Gerrit API responses, keyed by topic
      • groupA_topics_dataset.csv     – one row per topic with ALL features

Système de reprise / checkpoint
--------------------------------
Le fichier ``groupA_gerrit_raw.json`` sert AUSSI de checkpoint. Pour chaque
topic on stocke :

    {
      "<topic_id>": {
          "changes": [...],       # changes déjà récupérés
          "done": true/false,     # topic entièrement téléchargé ?
          "next_start": <int>     # offset de pagination pour reprendre
      },
      ...
    }

La sauvegarde se fait :
  - après CHAQUE page de résultats Gerrit téléchargée avec succès
    (pas seulement à la fin d'un topic) ;
  - via écriture atomique (fichier temporaire + remplacement) pour éviter
    un fichier corrompu si le courant coupe pendant l'écriture.

En cas de coupure réseau, le script NE PLANTE PAS : il réessaie
indéfiniment avec un délai croissant (plafonné), et reprend automatiquement
dès que la connexion revient — sans rien retélécharger.

Si vous arrêtez le script manuellement (Ctrl+C) ou s'il est interrompu
(coupure de courant), il vous suffit de le relancer avec LA MÊME COMMANDE :
il reprendra exactement où il s'est arrêté (même topic, même page).

Usage
-----
    python build_groupA_dataset.py

    # Dry-run sur les 3 premiers blueprints seulement
    python build_groupA_dataset.py --limit 3

    # Ignorer le checkpoint existant et repartir de zéro
    python build_groupA_dataset.py --fresh

    # Utiliser une autre base URL Gerrit
    python build_groupA_dataset.py --base-url https://review.opendev.org
"""

