def count_ci_verifications(change: dict[str, Any], bot_accounts: set[int]) -> tuple[int, int]:
    votes = ((change.get("labels") or {}).get("Verified") or {}).get("all") or []
    successes = failures = 0
    for v in votes:
        try:
            acct = int(v.get("_account_id", -1))
        except (TypeError, ValueError):
            continue
        if acct not in bot_accounts:
            continue
        val = v.get("value") or 0
        if val > 0:
            successes += 1
        elif val < 0:
            failures += 1
    return successes, failures


def count_verified_reruns(change: dict[str, Any], bot_accounts: set[int]) -> int:
    votes = ((change.get("labels") or {}).get("Verified") or {}).get("all") or []
    ci_votes = [
        v.get("value", 0) or 0
        for v in votes
        if int(v.get("_account_id", -1)) in bot_accounts
    ]
    reruns, had_positive = 0, False
    for val in ci_votes:
        if val > 0:
            had_positive = True
        elif had_positive and val <= 0:
            reruns += 1
            had_positive = False
    return reruns


def count_recheck_messages(change: dict[str, Any]) -> int:
    return sum(
        1
        for msg in (change.get("messages") or [])
        if "recheck" in (msg.get("message") or "").lower()
    )


def collect_reviewer_ids(change: dict[str, Any]) -> set[int]:
    ids: set[int] = set()
    for label_info in (change.get("labels") or {}).values():
        for vote in (label_info.get("all") or []):
            a = vote.get("_account_id")
            if a is not None:
                ids.add(int(a))
    for msg in (change.get("messages") or []):
        a = (msg.get("author") or {}).get("_account_id")
        if a is not None:
            ids.add(int(a))
    return ids


def extract_code_review_labels(change: dict[str, Any]) -> tuple[int, int]:
    votes = ((change.get("labels") or {}).get("Code-Review") or {}).get("all") or []
    plus2 = minus2 = 0
    for vote in votes:
        val = vote.get("value") or 0
        if val == 2:
            plus2 += 1
        elif val == -2:
            minus2 += 1
    return plus2, minus2


def calculate_review_delays(change: dict[str, Any], bot_accounts: set[int]) -> tuple[float | None, float | None]:
    created = parse_gerrit_ts(change.get("created"))
    if not created:
        return None, None
    owner = change.get("owner") or {}
    owner_acct = owner.get("_account_id")
    owner_uname = owner.get("username")
    deltas: list[float] = []
    for msg in (change.get("messages") or []):
        author = msg.get("author") or {}
        if owner_acct is not None and author.get("_account_id") == owner_acct:
            continue
        if owner_uname and author.get("username") == owner_uname:
            continue
        if _is_bot_message(msg, bot_accounts):
            continue
        t = parse_gerrit_ts(msg.get("date"))
        if t is None:
            continue
        d = (t - created).total_seconds() / 3600.0
        if d >= 0:
            deltas.append(d)
    if not deltas:
        return None, None
    return min(deltas), statistics.mean(deltas)


def get_code_authors(change: dict[str, Any]) -> set[str]:
    authors: set[str] = set()
    owner = change.get("owner") or {}
    uid = owner.get("email") or owner.get("username")
    if uid:
        authors.add(uid)
    for rev in (change.get("revisions") or {}).values():
        uploader = rev.get("uploader") or {}
        uid = uploader.get("email") or uploader.get("username")
        if uid:
            authors.add(uid)
    return authors


def get_people_involved(change: dict[str, Any], bot_accounts: set[int]) -> set[str]:
    people: set[str] = set(get_code_authors(change))
    for msg in (change.get("messages") or []):
        if _is_bot_message(msg, bot_accounts):
            continue
        author = msg.get("author") or {}
        uid = author.get("email") or author.get("username")
        if uid:
            people.add(uid)
    return people


def get_active_days(change: dict[str, Any]) -> int | None:
    created = parse_gerrit_ts(change.get("created"))
    updated = parse_gerrit_ts(change.get("updated"))
    if not created or not updated:
        return None
    return (updated - created).days


def get_patchset_stats(change: dict[str, Any]) -> tuple[int, int | None]:
    revisions = change.get("revisions") or {}
    total_ps = len(revisions)
    file_counts = [
        len(rev["files"])
        for rev in revisions.values()
        if isinstance(rev.get("files"), dict)
    ]
    return total_ps, (max(file_counts) if file_counts else None)


def get_top_author_changes(changes: list[dict[str, Any]]) -> int:
    counts: dict[str, int] = {}
    for change in changes:
        owner = change.get("owner") or {}
        author = owner.get("email") or owner.get("username") or "unknown"
        counts[author] = counts.get(author, 0) + 1
    return max(counts.values()) if counts else 0


def classify_outcome(statuses: list[str], last_updated: datetime | None, now: datetime) -> str:
    """
    Determine the high-level outcome label for a topic.

    IMPORTANT: a topic's lifecycle is COMPLETE as soon as every change in it has
    reached a terminal Gerrit status (MERGED or ABANDONED) -- i.e. there is no
    change left with status NEW/OPEN/DRAFT. This is true even when the topic
    mixes merged and abandoned changes.
    """
    unique = {s.upper() for s in statuses}
    if unique == {"MERGED"}:
        return "merged"
    if unique == {"ABANDONED"}:
        return "abandoned"

    # Lifecycle complete but mixed success: no NEW/open change remains.
    if "NEW" not in unique:
        return "completed_mixed"

    if last_updated and (now - last_updated).days > STALE_OPEN_DAYS:
        return "stale_open"
    return "mixed"  # genuinely still in progress (at least one open change)


