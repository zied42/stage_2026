def main() -> None:
    if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--base-url",
        default=DEFAULT_BASE_URL,
        help=f"Gerrit base URL (default: {DEFAULT_BASE_URL})",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process only the first N blueprints (for testing).",
    )
    parser.add_argument(
        "--fresh",
        action="store_true",
        help=f"Ignorer le checkpoint existant dans {RAW_OUTPUT} et repartir de zéro "
             f"(par défaut, le script reprend automatiquement).",
    )
    args = parser.parse_args()

    try:
        run(base_url=args.base_url, limit=args.limit, fresh=args.fresh)
    except KeyboardInterrupt:
        print("\n[INFO] Arrêt manuel demandé. La progression a déjà été sauvegardée.")
        print("       Relancez la même commande pour reprendre où vous étiez.")
        sys.exit(1)


if __name__ == "__main__":
    main()