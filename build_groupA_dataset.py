def load_blueprints(path: Path) -> list[dict[str, Any]]:
    print(f"Loading blueprints from {path} …")
    with path.open("r", encoding="utf-8") as fh:
        blueprints = json.load(fh)
    print(f"  {len(blueprints):,} blueprints loaded.")
    return blueprints


def run(base_url: str, limit: int | None, fresh: bool) -> None:
    now = datetime.now(tz=timezone.utc)

    blueprints = load_blueprints(INPUT_JSON)
    if limit:
        blueprints = blueprints[:limit]
        print(f"  (limited to first {limit})")

    # ── Chargement automatique du checkpoint ────────────────────────────────
    raw_data: dict[str, dict[str, Any]] = {} if fresh else load_checkpoint(RAW_OUTPUT)
    if raw_data:
        n_done = sum(1 for v in raw_data.values() if v.get("done"))
        n_partial = len(raw_data) - n_done
        print(f"Reprise automatique depuis {RAW_OUTPUT} : "
              f"{n_done} topic(s) complet(s), {n_partial} en cours/à reprendre.")
    elif fresh:
        print("Option --fresh : le checkpoint existant est ignoré, on repart de zéro.")

    session = requests.Session()
    session.headers.update({"Accept": "application/json"})

    topic_to_changes: dict[str, list[dict[str, Any]]] = {}
    interrupted = False

    print("\n-- Phase 1: Fetching Gerrit changes ------------------------------------")
    try:
        for i, bp in enumerate(blueprints, 1):
            name = bp.get("blueprint") or bp.get("name", f"bp_{i}")
            urls: list[str] = bp.get("gerrit_topics") or []
            print(f"\n[{i}/{len(blueprints)}] {name} ({len(urls)} topic URL(s))")

            for url in urls:
                topic = topic_from_url(url)
                if not topic:
                    print(f"  [SKIP] Cannot parse topic from: {url}")
                    continue

                if topic in topic_to_changes:
                    print(f"  [CACHED] {topic!r} déjà traité cette exécution.")
                    continue

                entry = raw_data.get(topic)

                if entry and entry.get("done"):
                    print(f"  [OK] {topic!r} déjà complet "
                          f"({len(entry['changes'])} changes) — on passe au suivant.")
                    topic_to_changes[topic] = entry["changes"]
                    continue

                if entry:
                    changes = entry["changes"]
                    start = entry.get("next_start", len(changes))
                    print(f"  [REPRISE] {topic!r} : reprise à l'offset {start} "
                          f"({len(changes)} changes déjà en cache).")
                else:
                    changes = []
                    start = 0
                    print(f"  Fetching topic: {topic!r} …")
                    raw_data[topic] = {"changes": changes, "done": False, "next_start": 0}

                def on_progress(cur_changes, cur_start, done, _topic=topic):
                    # Checkpoint immédiat après CHAQUE page téléchargée
                    raw_data[_topic] = {
                        "changes": cur_changes,
                        "done": done,
                        "next_start": cur_start,
                    }
                    save_checkpoint(RAW_OUTPUT, raw_data)

                try:
                    fetch_topic_changes(session, base_url, topic, changes, start, on_progress)
                except KeyboardInterrupt:
                    interrupted = True
                    raise
                except Exception as exc:  # noqa: BLE001 - on ne veut jamais perdre le run
                    print(f"  [ERREUR] {topic!r} : {exc} — progression conservée, "
                          f"on passe au topic suivant (celui-ci sera repris au prochain lancement).")
                    raw_data[topic] = {
                        "changes": changes,
                        "done": False,
                        "next_start": start,
                    }
                    save_checkpoint(RAW_OUTPUT, raw_data)
                    continue

                topic_to_changes[topic] = raw_data[topic]["changes"]
                print(f"    -> {len(topic_to_changes[topic])} change(s) au total pour ce topic.")
                time.sleep(REQUEST_DELAY)

    except KeyboardInterrupt:
        interrupted = True

    # Sauvegarde finale de sécurité (même contenu, mais on ne prend pas de risque)
    save_checkpoint(RAW_OUTPUT, raw_data)

    if interrupted:
        n_done = sum(1 for v in raw_data.values() if v.get("done"))
        print("\n" + "=" * 70)
        print("[INTERROMPU] Extraction arrêtée avant la fin (coupure réseau/courant ou Ctrl+C).")
        print(f"  Progression sauvegardée : {n_done}/{len(raw_data)} topic(s) complet(s) "
              f"dans {RAW_OUTPUT}.")
        print("  Relancez simplement la MÊME commande : le script reprendra exactement")
        print("  où il s'est arrêté (même topic, même page), sans rien retélécharger.")
        print("=" * 70)
        return

    not_done = [t for t, v in raw_data.items() if not v.get("done")]
    if not_done:
        print(f"\n[ATTENTION] {len(not_done)} topic(s) restent incomplets "
              f"(probablement suite à une interruption antérieure).")
        print("  Relancez le script pour terminer leur extraction avant de considérer")
        print("  le dataset comme définitif. On continue quand même avec les données")
        print("  actuellement disponibles pour générer un CSV provisoire.")

    print(f"\nSaving raw data -> {RAW_OUTPUT}")
    save_checkpoint(RAW_OUTPUT, raw_data)
    print(f"  OK {len(raw_data)} topics saved.")

    # ── Phase 2: Global bot account discovery ──────────────────────────────
    print("\n-- Phase 2: Bot account discovery --------------------------------------")
    all_changes_flat: list[dict[str, Any]] = []
    for changes in topic_to_changes.values():
        all_changes_flat.extend(changes)
    bot_accounts = discover_zuul_accounts(all_changes_flat)
    print(f"  Found {len(bot_accounts)} bot account(s): {sorted(bot_accounts)[:10]}")

    # ── Phase 3: Aggregate + merge ─────────────────────────────────────────
    print("\n-- Phase 3: Aggregating topic metrics & merging Launchpad data --------")
    rows: list[dict[str, Any]] = []

    for bp in blueprints:
        name = bp.get("blueprint") or bp.get("name", "")
        urls: list[str] = bp.get("gerrit_topics") or []

        lp_meta: dict[str, Any] = {f: bp.get(f) for f in LP_FIELDS}
        lp_meta["blueprint"] = lp_meta.get("blueprint") or lp_meta.get("name")

        if not urls:
            row: dict[str, Any] = dict(lp_meta)
            row.update({
                "topic_id": None, "subject": None,
                "n_changes": 0, "n_repos": 0, "n_branches": 0,
                "n_merged": 0, "n_abandoned": 0, "n_open": 0,
                "outcome": "no_gerrit",
                "topic_lifecycle_complete": False,
                "completed_with_partial_success": False,
            })
            rows.append(row)
            continue

        for url in urls:
            topic = topic_from_url(url)
            if not topic:
                continue

            changes = topic_to_changes.get(topic, [])
            if changes:
                gerrit_row = aggregate_topic(topic, changes, bot_accounts, now)
            else:
                gerrit_row = {
                    "topic_id": topic, "subject": "",
                    "n_changes": 0, "n_repos": 0, "n_branches": 0,
                    "n_merged": 0, "n_abandoned": 0, "n_open": 0,
                    "outcome": "empty",
                }

            row = dict(lp_meta)
            row.update(gerrit_row)
            rows.append(row)

    # ── Phase 4: Write CSV ─────────────────────────────────────────────────
    print(f"\n-- Phase 4: Writing CSV -> {CSV_OUTPUT} --------------------------------")
    with CSV_OUTPUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"  OK {len(rows)} rows written.")

    print("\n" + "=" * 70)
    print("Pipeline complete.")
    print(f"  Raw Gerrit data  -> {RAW_OUTPUT}  ({len(raw_data)} topics)")
    print(f"  Topic dataset    -> {CSV_OUTPUT}   ({len(rows)} rows)")
    print("=" * 70)


