_INVALID_TOPIC_CHARS = re.compile(r"[()\s<>\"'\\]")


def topic_from_url(url: str) -> str | None:
    m = re.search(r"topic:([^,\s&]+)", url)
    if not m:
        return None
    topic = m.group(1)
    if _INVALID_TOPIC_CHARS.search(topic):
        return None
    if len(topic) < 2:
        return None
    return topic


def build_gerrit_query(topic: str) -> str:
    return f"topic:{topic}"


