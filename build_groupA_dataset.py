def _strip_prefix(raw: bytes) -> bytes:
    for i, b in enumerate(raw):
        if b in (ord("["), ord("{")):
            return raw[i:]
    return raw


def fetch_topic_changes(
    session: requests.Session,
    base_url: str,
    topic: str,
    changes: list[dict[str, Any]],
    start: int,
    on_progress: Callable[[list[dict[str, Any]], int, bool], None],
) -> None:
    """
    Télécharge (en reprenant à *start*) toutes les pages restantes pour
    *topic*, en ajoutant directement dans *changes* (in place).

    Appelle on_progress(changes, next_start, done) après CHAQUE page réussie,
    afin de checkpointer la progression immédiatement.

    En cas d'erreur réseau : réessaie indéfiniment avec un backoff plafonné
    (ne perd jamais la progression déjà faite). Ctrl+C lève KeyboardInterrupt
    qui est propagée à l'appelant (la progression est déjà sauvegardée).
    """
    query = build_gerrit_query(topic)
    url = f"{base_url}/changes/"
    retry_count = 0

    while True:
        params: list[tuple[str, str]] = [
            ("q", query),
            ("n", str(GERRIT_MAX_PAGE_SIZE)),
            ("S", str(start)),
        ]
        for opt in GERRIT_OPTIONS:
            params.append(("o", opt))

        try:
            resp = session.get(url, params=params, timeout=60)

            if 400 <= resp.status_code < 500:
                print(f"    [SKIP] HTTP {resp.status_code} pour topic={topic!r} "
                      f"(erreur client, on n'insiste pas).")
                on_progress(changes, start, True)
                return

            if resp.status_code >= 500:
                raise requests.HTTPError(f"HTTP {resp.status_code}")

            resp.raise_for_status()
            data = json.loads(_strip_prefix(resp.content))
            retry_count = 0  # succès -> on réinitialise le backoff

        except (requests.RequestException, json.JSONDecodeError) as exc:
            retry_count += 1
            wait = min(RETRY_BACKOFF_BASE ** retry_count, MAX_WAIT_SECONDS)
            print(f"    [RESEAU] Connexion interrompue ({exc}). "
                  f"Nouvelle tentative dans {wait:.0f}s… "
                  f"(progression déjà sauvegardée, vous pouvez arrêter et "
                  f"relancer sans rien perdre)")
            time.sleep(wait)   # KeyboardInterrupt remonte naturellement ici
            continue            # on retente EXACTEMENT la même page

        # Page reçue avec succès -> on l'intègre et on checkpointe direct
        page_changes = [c for c in data if not (len(c) == 1 and "_more_changes" in c)]
        changes.extend(page_changes)
        start += len(page_changes)

        more = bool(data) and data[-1].get("_more_changes", False)
        on_progress(changes, start, not more)   # <-- checkpoint après CHAQUE page

        if not more:
            return

        time.sleep(REQUEST_DELAY)


