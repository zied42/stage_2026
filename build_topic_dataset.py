def count_ci_verifications(
    change: dict[str, Any], bot_accounts: set[int]
) -> tuple[int, int]:
    """
    Count CI verification successes and failures for a single change.

    Each CI-bot Verified vote is classified individually:

    * ``value > 0`` → success
    * ``value < 0`` → failure
    * ``value == 0`` → ignored (transient / reset)

    Parameters
    ----------
    change:
        Single Gerrit change dict.
    bot_accounts:
        Set of account IDs identified as CI bots.

    Returns
    -------
    tuple[int, int]
        ``(ci_successes, ci_failures)``
    """
    labels: dict[str, Any] = change.get("labels") or {}
    verified_info: dict[str, Any] = labels.get("Verified") or {}
    votes: list[dict[str, Any]] = verified_info.get("all", []) or []

    successes = 0
    failures = 0
    for v in votes:
        try:
            acct_id = int(v.get("_account_id", -1))
        except (TypeError, ValueError):
            continue
        if acct_id not in bot_accounts:
            continue
        value = v.get("value") or 0
        if value > 0:
            successes += 1
        elif value < 0:
            failures += 1
    return successes, failures


def count_verified_reruns(change: dict[str, Any], bot_accounts: set[int]) -> int:
    """
    Count Verified label *re-run* events for a single change.

    A re-run is a transition of the Verified vote from a prior positive value
    to ``<= 0`` from a CI bot account.  Kept for backwards compatibility with
    the original ``ci_rerun_verified_drops`` column.
    """
    labels: dict[str, Any] = change.get("labels") or {}
    verified_info: dict[str, Any] = labels.get("Verified") or {}
    votes: list[dict[str, Any]] = verified_info.get("all", []) or []

    ci_votes = [
        v.get("value", 0) or 0
        for v in votes
        if int(v.get("_account_id", -1)) in bot_accounts
    ]

    reruns = 0
    had_positive = False
    for value in ci_votes:
        if value > 0:
            had_positive = True
        elif had_positive and value <= 0:
            reruns += 1
            had_positive = False
    return reruns


def count_recheck_messages(change: dict[str, Any]) -> int:
    """Count messages containing ``"recheck"`` (case-insensitive)."""
    messages: list[dict[str, Any]] = change.get("messages") or []
    return sum(
        1
        for msg in messages
        if "recheck" in (msg.get("message") or "").lower()
    )


