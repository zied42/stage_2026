def extract_code_review_labels(change: dict[str, Any]) -> tuple[int, int]:
    """Extract Code-Review +2 and -2 vote counts from a change."""
    labels: dict[str, Any] = change.get("labels") or {}
    code_review_info: dict[str, Any] = labels.get("Code-Review") or {}
    votes: list[dict[str, Any]] = code_review_info.get("all", []) or []

    plus2 = 0
    minus2 = 0
    for vote in votes:
        value = vote.get("value") or 0
        if value == 2:
            plus2 += 1
        elif value == -2:
            minus2 += 1
    return plus2, minus2


def calculate_review_delays(
    change: dict[str, Any],
    bot_accounts: set[int],
) -> tuple[float | None, float | None]:
    """
    Calculate first review delay and average review delay for a change.

    Bias fixes:

    * Skip messages from the change owner (the author itself).
    * Skip CI/bot messages identified by tag, account id or username hint.
    * Skip empty/auto-generated body messages where the body equals the tag.

    Parameters
    ----------
    change:
        Single Gerrit change dict.
    bot_accounts:
        Set of account IDs identified as CI bots.

    Returns
    -------
    tuple[float | None, float | None]
        ``(first_review_delay_hours, avg_review_delay_hours)``.
        Both ``None`` when no human review messages were found.
    """
    created = parse_gerrit_ts(change.get("created"))
    if not created:
        return None, None

    owner = change.get("owner") or {}
    owner_username = owner.get("username")
    owner_acct_id = owner.get("_account_id")

    messages: list[dict[str, Any]] = change.get("messages") or []
    review_deltas_hours: list[float] = []

    for msg in messages:
        author = msg.get("author") or {}

        # Skip the change owner
        if owner_acct_id is not None and author.get("_account_id") == owner_acct_id:
            continue
        if owner_username and author.get("username") == owner_username:
            continue

        # Skip CI / bot messages
        if _is_bot_message(msg, bot_accounts):
            continue

        msg_time = parse_gerrit_ts(msg.get("date"))
        if msg_time is None:
            continue

        delta = (msg_time - created).total_seconds() / 3600.0
        # Negative deltas can occur due to clock skew; ignore them
        if delta < 0:
            continue
        review_deltas_hours.append(delta)

    if not review_deltas_hours:
        return None, None

    first_delay_hours = min(review_deltas_hours)
    avg_delay_hours = statistics.mean(review_deltas_hours)
    return first_delay_hours, avg_delay_hours


def get_code_authors(change: dict[str, Any]) -> set[str]:
    """
    Return strict "code author" identities for a change: the owner plus all
    distinct uploaders of any revision.  These are the people who *wrote*
    code, not those who merely reviewed it.
    """
    authors: set[str] = set()

    owner = change.get("owner") or {}
    owner_id = owner.get("email") or owner.get("username")
    if owner_id:
        authors.add(owner_id)

    revisions: dict[str, Any] = change.get("revisions") or {}
    for rev in revisions.values():
        uploader = rev.get("uploader") or {}
        uid = uploader.get("email") or uploader.get("username")
        if uid:
            authors.add(uid)

    return authors


def get_people_involved(
    change: dict[str, Any],
    bot_accounts: set[int],
) -> set[str]:
    """
    Return the set of all distinct *human* identities involved in a change:
    owner, uploaders and message authors, excluding CI/bot accounts.
    """
    people: set[str] = set(get_code_authors(change))

    for msg in change.get("messages") or []:
        if _is_bot_message(msg, bot_accounts):
            continue
        author = msg.get("author") or {}
        uid = author.get("email") or author.get("username")
        if uid:
            people.add(uid)

    return people


def get_active_days(change: dict[str, Any]) -> int | None:
    """Number of days between change creation and last update."""
    created = parse_gerrit_ts(change.get("created"))
    updated = parse_gerrit_ts(change.get("updated"))
    if not created or not updated:
        return None
    return (updated - created).days


def get_patchset_stats(change: dict[str, Any]) -> tuple[int, int | None]:
    """
    Return ``(total_patchsets, max_files_changed)``.

    * ``total_patchsets`` — number of revisions/patchsets uploaded.
    * ``max_files_changed`` — the largest number of files touched in any
      single patchset.  ``None`` if no patchset has a ``files`` listing
      (e.g. when the collector didn't request it).
    """
    revisions: dict[str, Any] = change.get("revisions") or {}
    total_patchsets = len(revisions)

    file_counts: list[int] = []
    for rev in revisions.values():
        files = rev.get("files")
        if isinstance(files, dict):
            file_counts.append(len(files))

    max_files_changed = max(file_counts) if file_counts else None
    return total_patchsets, max_files_changed


def get_top_author_changes(changes: list[dict[str, Any]]) -> int:
    """Maximum number of changes authored (owned) by a single contributor."""
    counts: dict[str, int] = {}
    for change in changes:
        owner = change.get("owner") or {}
        author = owner.get("email") or owner.get("username") or "unknown"
        counts[author] = counts.get(author, 0) + 1
    return max(counts.values()) if counts else 0


