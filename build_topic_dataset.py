def _describe(values: list[float], label: str, unit: str = "") -> None:
    """Helper: print min / median / mean / max / nulls for a numeric series."""
    real = [v for v in values if v is not None]
    n_null = len(values) - len(real)
    if not real:
        print(f"    {label:<35} (all null, n={len(values)})")
        return
    print(
        f"    {label:<35} "
        f"min={min(real):>9.2f}{unit}  "
        f"med={statistics.median(real):>9.2f}{unit}  "
        f"mean={statistics.mean(real):>9.2f}{unit}  "
        f"max={max(real):>9.2f}{unit}  "
        f"nulls={n_null}"
    )


def _pearson(xs: list[float], ys: list[float]) -> float | None:
    """Pearson correlation, ``None`` when undefined."""
    pairs = [(x, y) for x, y in zip(xs, ys) if x is not None and y is not None]
    if len(pairs) < 3:
        return None
    xa = [p[0] for p in pairs]
    ya = [p[1] for p in pairs]
    try:
        mx = statistics.mean(xa)
        my = statistics.mean(ya)
        num = sum((x - mx) * (y - my) for x, y in pairs)
        dx = math_sqrt(sum((x - mx) ** 2 for x in xa))
        dy = math_sqrt(sum((y - my) ** 2 for y in ya))
        if dx == 0 or dy == 0:
            return None
        return num / (dx * dy)
    except statistics.StatisticsError:
        return None


def math_sqrt(x: float) -> float:
    """Tiny local sqrt so we don't add another import for one call."""
    return x ** 0.5


def verify_feature_quality(topic_rows: list[dict[str, Any]]) -> None:
    """
    Print sanity-check distributions and correlations for the engineered
    topic-level features, so reviewers can spot suspicious ranges or
    impossible values at a glance.

    Parameters
    ----------
    topic_rows:
        Aggregated topic dicts, as produced by :func:`aggregate_topic`.
    """
    print("\n" + "=" * 70)
    print("Feature Quality Verification")
    print("=" * 70)

    if not topic_rows:
        print("  (No topics — nothing to verify.)")
        return

    n = len(topic_rows)
    print(f"  Topics analysed: {n}")

    # ---- Distributions of numeric features ----
    print("\n  Numeric feature distributions:")
    numeric_fields = [
        ("n_changes", ""),
        ("total_revisions", ""),
        ("total_messages", ""),
        ("n_reviewers", ""),
        ("total_code_review_plus2", ""),
        ("total_code_review_minus2", ""),
        ("first_review_delay_hours", "h"),
        ("avg_review_delay_hours", "h"),
        ("avg_active_days", "d"),
        ("total_patchsets", ""),
        ("avg_patchsets_per_change", ""),
        ("max_files_changed", ""),
        ("ci_runs", ""),
        ("ci_successes", ""),
        ("ci_failures", ""),
        ("ci_failure_rate", ""),
        ("ci_retries", ""),
        ("people_involved_count", ""),
        ("code_authors_count", ""),
        ("authors_per_change", ""),
        ("top_author_changes", ""),
    ]
    for field, unit in numeric_fields:
        _describe([r.get(field) for r in topic_rows], field, unit)

    # ---- Sanity checks ----
    print("\n  Sanity checks:")
    bad_failure_rate = sum(
        1 for r in topic_rows
        if r.get("ci_failure_rate") is not None
        and not (0.0 <= r["ci_failure_rate"] <= 1.0)
    )
    print(f"    ci_failure_rate outside [0, 1]   : {bad_failure_rate}")

    bad_runs = sum(
        1 for r in topic_rows
        if (r.get("ci_successes") or 0) + (r.get("ci_failures") or 0)
        != (r.get("ci_runs") or 0)
    )
    print(f"    ci_runs != successes + failures  : {bad_runs}")

    negative_delays = sum(
        1 for r in topic_rows
        if (r.get("first_review_delay_hours") or 0) < 0
        or (r.get("avg_review_delay_hours") or 0) < 0
    )
    print(f"    Negative review delays           : {negative_delays}")

    avg_gt_max_files = sum(
        1 for r in topic_rows
        if r.get("avg_patchsets_per_change") is not None
        and r.get("total_patchsets") is not None
        and r["avg_patchsets_per_change"] > max(r["total_patchsets"], 1)
    )
    print(f"    avg_patchsets_per_change > total : {avg_gt_max_files}")

    code_gt_people = sum(
        1 for r in topic_rows
        if (r.get("code_authors_count") or 0) > (r.get("people_involved_count") or 0)
    )
    print(f"    code_authors > people_involved   : {code_gt_people}")

    top_gt_changes = sum(
        1 for r in topic_rows
        if (r.get("top_author_changes") or 0) > (r.get("n_changes") or 0)
    )
    print(f"    top_author_changes > n_changes   : {top_gt_changes}")

    # ---- Coverage (% non-null) ----
    print("\n  Coverage (% of topics with a non-null value):")
    for field, _ in numeric_fields:
        non_null = sum(1 for r in topic_rows if r.get(field) is not None)
        print(f"    {field:<35} {100*non_null/n:6.1f}%  ({non_null}/{n})")

    # ---- A few interesting correlations ----
    print("\n  Selected correlations:")
    pairs = [
        ("n_changes", "total_patchsets"),
        ("n_changes", "ci_runs"),
        ("ci_failures", "ci_retries"),
        ("first_review_delay_hours", "avg_review_delay_hours"),
        ("total_code_review_minus2", "ci_failures"),
        ("people_involved_count", "n_changes"),
    ]
    for a, b in pairs:
        xs = [r.get(a) for r in topic_rows]
        ys = [r.get(b) for r in topic_rows]
        corr = _pearson(xs, ys)
        corr_str = f"{corr:+.3f}" if corr is not None else "  n/a "
        print(f"    corr({a}, {b}) = {corr_str}")

    # ---- Outcome-conditioned medians ----
    print("\n  Median feature values by outcome:")
    by_outcome: dict[str, list[dict[str, Any]]] = {}
    for r in topic_rows:
        by_outcome.setdefault(r["outcome"], []).append(r)
    interesting = [
        "n_changes",
        "first_review_delay_hours",
        "avg_review_delay_hours",
        "ci_failure_rate",
        "total_code_review_minus2",
        "total_patchsets",
    ]
    header = "    " + "outcome".ljust(15) + "".join(f"{f[:18]:>20}" for f in interesting)
    print(header)
    for outcome, rs in sorted(by_outcome.items()):
        line = "    " + outcome.ljust(15)
        for f in interesting:
            vs = [r.get(f) for r in rs if r.get(f) is not None]
            line += f"{statistics.median(vs):>20.2f}" if vs else f"{'n/a':>20}"
        print(line)

    print("=" * 70)


