def _is_ci_tag(tag: str | None, prefixes: tuple[str, ...] = CI_TAG_PREFIXES) -> bool:
    """Return ``True`` if *tag* matches any of the configured CI prefixes."""
    if not tag:
        return False
    return any(tag.startswith(prefix) for prefix in prefixes)


def _looks_like_bot_username(username: str | None) -> bool:
    """Heuristic fallback: return ``True`` if *username* contains a bot hint."""
    if not username:
        return False
    uname = username.lower()
    return any(hint in uname for hint in BOT_USERNAME_HINTS)


def discover_zuul_accounts(changes: list[dict[str, Any]]) -> set[int]:
    """
    Scan all label votes and message tags across all changes to discover
    account IDs associated with autogenerated CI tags.
    """
    bot_accounts: set[int] = set()
    for change in changes:
        # Votes
        labels: dict[str, Any] = change.get("labels") or {}
        for label_info in labels.values():
            for vote in label_info.get("all", []) or []:
                if _is_ci_tag(vote.get("tag")):
                    acct_id = vote.get("_account_id")
                    if acct_id is not None:
                        bot_accounts.add(int(acct_id))
        # Messages (tag is also present on automated messages)
        for msg in change.get("messages") or []:
            if _is_ci_tag(msg.get("tag"), CI_MESSAGE_TAG_PREFIXES):
                author = msg.get("author") or {}
                acct_id = author.get("_account_id")
                if acct_id is not None:
                    bot_accounts.add(int(acct_id))
    return bot_accounts


def _is_bot_message(msg: dict[str, Any], bot_accounts: set[int]) -> bool:
    """
    Determine whether a single message was posted by a CI bot.

    Tries three signals, in order:
    1. ``tag`` field on the message starts with a known CI prefix.
    2. ``author._account_id`` is in *bot_accounts*.
    3. ``author.username`` contains a known bot hint (e.g. "zuul").
    """
    if _is_ci_tag(msg.get("tag"), CI_MESSAGE_TAG_PREFIXES):
        return True
    author = msg.get("author") or {}
    acct_id = author.get("_account_id")
    if acct_id is not None and int(acct_id) in bot_accounts:
        return True
    return _looks_like_bot_username(author.get("username"))


