"""
build_topic_dataset.py
======================
Loads all raw Gerrit change data from ``./raw_data/``, groups changes by their
``topic`` field, computes topic-level analytics and writes both CSV and Parquet
output files.

Usage:
    python build_topic_dataset.py

Outputs:
    topics_dataset.csv
    topics_dataset.parquet
"""

from __future__ import annotations

import csv
import json
import math
import re
import statistics
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import pyarrow as pa
import pyarrow.parquet as pq

# ---------------------------------------------------------------------------
# Configuration constants
# ---------------------------------------------------------------------------

#: Root directory that contains the raw JSON collected by collect_changes.py
RAW_DATA_DIR: Path = Path("raw_data")

#: Output CSV file path
OUTPUT_CSV: Path = Path("topics_dataset.csv")

#: Output Parquet file path
OUTPUT_PARQUET: Path = Path("topics_dataset.parquet")

#: Topics whose n_changes exceeds this threshold are flagged for manual review.
LARGE_TOPIC_THRESHOLD: int = 50

#: An open change with no activity for more than this many days is "stale".
STALE_OPEN_DAYS: int = 90

#: Prefix strings used in Gerrit label vote tag fields that identify CI bots.
CI_TAG_PREFIXES: tuple[str, ...] = ("autogenerated:zuul",)

# ---------------------------------------------------------------------------
# Datetime helpers
# ---------------------------------------------------------------------------

_GERRIT_TS_FORMATS: list[str] = [
    "%Y-%m-%d %H:%M:%S.%f000",   # with microseconds (Gerrit default)
    "%Y-%m-%d %H:%M:%S.%f",
    "%Y-%m-%d %H:%M:%S",
]


def parse_gerrit_ts(ts: str | None) -> datetime | None:
    """
    Parse a Gerrit timestamp string into an aware UTC :class:`datetime`.

    Gerrit returns timestamps as ``"YYYY-MM-DD HH:MM:SS.000000000"`` (nine
    fractional digits, but Python's ``%f`` only consumes six).  We strip the
    trailing three digits before parsing.

    Parameters
    ----------
    ts:
        Timestamp string from a Gerrit API response, or ``None``.

    Returns
    -------
    datetime | None
        Parsed UTC-aware datetime, or ``None`` if *ts* is falsy.
    """
    if not ts:
        return None
    # Normalise nine-digit fractional seconds → six
    ts_norm = re.sub(r"(\.\d{6})\d+", r"\1", ts)
    for fmt in _GERRIT_TS_FORMATS:
        try:
            dt = datetime.strptime(ts_norm, fmt)
            return dt.replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def hours_between(start: datetime | None, end: datetime | None) -> float | None:
    """
    Return elapsed hours between *start* and *end*, or ``None`` if either is
    missing.
    """
    if start is None or end is None:
        return None
    return (end - start).total_seconds() / 3600.0


# ---------------------------------------------------------------------------
# Raw data loading
# ---------------------------------------------------------------------------

def load_all_changes(raw_dir: Path) -> list[dict[str, Any]]:
    """
    Walk *raw_dir* and deserialise every ``page_*.json`` file found.

    Duplicate change numbers (same change appearing in multiple page files due
    to pagination overlap) are de-duplicated by ``id``.

    Parameters
    ----------
    raw_dir:
        Root of the raw data directory tree.

    Returns
    -------
    list[dict]
        Flat list of unique Gerrit change dicts.
    """
    seen_ids: set[str] = set()
    all_changes: list[dict[str, Any]] = []
    json_files = sorted(raw_dir.rglob("page_*.json"))

    if not json_files:
        raise FileNotFoundError(
            f"No page_*.json files found under {raw_dir!s}.  "
            "Run collect_changes.py first."
        )

    print(f"Loading raw data from {len(json_files)} file(s) …")

    for path in json_files:
        with path.open("r", encoding="utf-8") as fh:
            data = json.load(fh)
        for change in data:
            # Skip Gerrit sentinel / pagination marker entries
            if "_more_changes" in change and len(change) == 1:
                continue
            cid = change.get("id") or change.get("change_id") or change.get("_number")
            if cid in seen_ids:
                continue
            seen_ids.add(str(cid))
            all_changes.append(change)

    print(f"  Loaded {len(all_changes):,} unique changes.")
    return all_changes


# ---------------------------------------------------------------------------
# Zuul / CI bot detection
# ---------------------------------------------------------------------------

def _is_ci_tag(tag: str | None) -> bool:
    """Return ``True`` if *tag* looks like an autogenerated CI tag."""
    if not tag:
        return False
    return any(tag.startswith(prefix) for prefix in CI_TAG_PREFIXES)


def discover_zuul_accounts(changes: list[dict[str, Any]]) -> set[int]:
    """
    Scan all label votes across all changes to discover account IDs that are
    associated with autogenerated CI tags.

    Parameters
    ----------
    changes:
        Full list of loaded Gerrit change dicts.

    Returns
    -------
    set[int]
        Account IDs identified as CI/Zuul bots.
    """
    bot_accounts: set[int] = set()
    for change in changes:
        labels: dict[str, Any] = change.get("labels") or {}
        for _label_name, label_info in labels.items():
            for vote in label_info.get("all", []):
                tag = vote.get("tag")
                if _is_ci_tag(tag):
                    acct_id = vote.get("_account_id")
                    if acct_id is not None:
                        bot_accounts.add(int(acct_id))
    return bot_accounts


# ---------------------------------------------------------------------------
# CI re-run counting
# ---------------------------------------------------------------------------

def count_verified_reruns(change: dict[str, Any], bot_accounts: set[int]) -> int:
    """
    Count Verified label *re-run* events for a single change.

    A re-run is defined as a transition of the Verified vote into a negative
    or zero value *after* a prior positive value from a CI bot account.

    Parameters
    ----------
    change:
        Single Gerrit change dict.
    bot_accounts:
        Set of account IDs identified as CI bots.

    Returns
    -------
    int
        Number of Verified label re-run events detected.
    """
    labels: dict[str, Any] = change.get("labels") or {}
    verified_info: dict[str, Any] = labels.get("Verified") or {}
    votes: list[dict[str, Any]] = verified_info.get("all", [])

    # Filter to CI bot votes only, ordered by their implicit index in the list
    # (Gerrit returns them newest-last inside a revision scope, but across
    # revisions the ordering isn't guaranteed — we use the list order as proxy)
    ci_votes = [
        v.get("value", 0) or 0
        for v in votes
        if int(v.get("_account_id", -1)) in bot_accounts
    ]

    reruns = 0
    had_positive = False
    for value in ci_votes:
        if value > 0:
            had_positive = True
        elif had_positive and value <= 0:
            reruns += 1
            had_positive = False  # reset — only count the drop, not sustained 0
    return reruns


def count_recheck_messages(change: dict[str, Any]) -> int:
    """
    Count the number of messages containing the literal string ``"recheck"``
    (case-insensitive) in the change's message thread.

    Parameters
    ----------
    change:
        Single Gerrit change dict.

    Returns
    -------
    int
        Number of recheck-containing messages.
    """
    messages: list[dict[str, Any]] = change.get("messages") or []
    return sum(
        1
        for msg in messages
        if "recheck" in (msg.get("message") or "").lower()
    )


# ---------------------------------------------------------------------------
# Reviewer extraction
# ---------------------------------------------------------------------------

def collect_reviewer_ids(change: dict[str, Any]) -> set[int]:
    """
    Collect all distinct reviewer account IDs for a single change.

    Sources: label vote ``_account_id`` fields and message ``author``
    account IDs.

    Parameters
    ----------
    change:
        Single Gerrit change dict.

    Returns
    -------
    set[int]
        Set of account IDs that reviewed or commented.
    """
    ids: set[int] = set()

    labels: dict[str, Any] = change.get("labels") or {}
    for _label_name, label_info in labels.items():
        for vote in label_info.get("all", []):
            acct_id = vote.get("_account_id")
            if acct_id is not None:
                ids.add(int(acct_id))

    messages: list[dict[str, Any]] = change.get("messages") or []
    for msg in messages:
        author = msg.get("author") or {}
        acct_id = author.get("_account_id")
        if acct_id is not None:
            ids.add(int(acct_id))

    return ids


# ---------------------------------------------------------------------------
# Topic outcome classification
# ---------------------------------------------------------------------------

def classify_outcome(
    statuses: list[str],
    last_updated: datetime | None,
    now: datetime,
) -> str:
    """
    Determine the high-level outcome label for a topic.

    Rules (in priority order):

    1. All changes merged → ``"merged"``
    2. All changes abandoned → ``"abandoned"``
    3. Any open change with no activity for > :data:`STALE_OPEN_DAYS` → ``"stale_open"``
    4. Otherwise → ``"mixed"``

    Parameters
    ----------
    statuses:
        List of status strings (``"MERGED"`` / ``"ABANDONED"`` / ``"NEW"``)
        for every change in the topic.
    last_updated:
        Latest ``updated`` timestamp across all changes in the topic.
    now:
        Reference *now* timestamp used to compute staleness.

    Returns
    -------
    str
        One of ``"merged"``, ``"abandoned"``, ``"mixed"``, or ``"stale_open"``.
    """
    unique = set(s.upper() for s in statuses)
    if unique == {"MERGED"}:
        return "merged"
    if unique == {"ABANDONED"}:
        return "abandoned"
    if "NEW" in unique:
        if last_updated is not None:
            age_days = (now - last_updated).days
            if age_days > STALE_OPEN_DAYS:
                return "stale_open"
    return "mixed"


# ---------------------------------------------------------------------------
# Per-topic aggregation
# ---------------------------------------------------------------------------

def aggregate_topic(
    topic: str,
    changes: list[dict[str, Any]],
    bot_accounts: set[int],
    now: datetime,
) -> dict[str, Any]:
    """
    Compute all topic-level metrics from the raw list of changes belonging to
    that topic.

    Parameters
    ----------
    topic:
        Topic identifier string.
    changes:
        All Gerrit change dicts that share this topic.
    bot_accounts:
        CI/Zuul bot account IDs, used for re-run detection.
    now:
        Reference timestamp for staleness calculation.

    Returns
    -------
    dict
        Flat dictionary of topic-level metrics ready for CSV/Parquet output.
    """
    n_changes = len(changes)
    repos: set[str] = set()
    branches: set[str] = set()
    total_revisions = 0
    total_messages = 0
    reviewer_ids: set[int] = set()
    created_dts: list[datetime] = []
    updated_dts: list[datetime] = []
    submitted_dts: list[datetime] = []
    statuses: list[str] = []

    ci_rerun_verified_total = 0
    ci_rerun_recheck_total = 0

    n_merged = n_abandoned = n_open = 0

    for change in changes:
        repos.add(change.get("project", ""))
        branches.add(change.get("branch", ""))

        revisions: dict[str, Any] = change.get("revisions") or {}
        total_revisions += len(revisions)

        messages: list[dict[str, Any]] = change.get("messages") or []
        total_messages += len(messages)

        reviewer_ids |= collect_reviewer_ids(change)

        dt_created = parse_gerrit_ts(change.get("created"))
        if dt_created:
            created_dts.append(dt_created)

        dt_updated = parse_gerrit_ts(change.get("updated"))
        if dt_updated:
            updated_dts.append(dt_updated)

        status = (change.get("status") or "").upper()
        statuses.append(status)

        if status == "MERGED":
            n_merged += 1
            dt_submitted = parse_gerrit_ts(change.get("submitted"))
            if dt_submitted:
                submitted_dts.append(dt_submitted)
        elif status == "ABANDONED":
            n_abandoned += 1
        else:
            n_open += 1

        ci_rerun_verified_total += count_verified_reruns(change, bot_accounts)
        ci_rerun_recheck_total += count_recheck_messages(change)

    created_at = min(created_dts) if created_dts else None
    last_updated_at = max(updated_dts) if updated_dts else None

    # time_to_completion: only valid when ALL changes are merged
    time_to_completion_hours: float | None = None
    if n_merged == n_changes and submitted_dts and created_dts:
        time_to_completion_hours = hours_between(
            min(created_dts), max(submitted_dts)
        )

    outcome = classify_outcome(statuses, last_updated_at, now)

    return {
        "topic_id": topic,
        "n_changes": n_changes,
        "n_repos": len(repos),
        "n_branches": len(branches),
        "total_revisions": total_revisions,
        "total_messages": total_messages,
        "n_reviewers": len(reviewer_ids),
        "created_at": created_at.isoformat() if created_at else None,
        "last_updated_at": last_updated_at.isoformat() if last_updated_at else None,
        "time_to_completion_hours": (
            round(time_to_completion_hours, 2)
            if time_to_completion_hours is not None
            else None
        ),
        "n_merged": n_merged,
        "n_abandoned": n_abandoned,
        "n_open": n_open,
        "outcome": outcome,
        "ci_rerun_verified_drops": ci_rerun_verified_total,
        "ci_rerun_recheck_msgs": ci_rerun_recheck_total,
    }


# ---------------------------------------------------------------------------
# Output writers
# ---------------------------------------------------------------------------

_CSV_FIELDS: list[str] = [
    "topic_id",
    "n_changes",
    "n_repos",
    "n_branches",
    "total_revisions",
    "total_messages",
    "n_reviewers",
    "created_at",
    "last_updated_at",
    "time_to_completion_hours",
    "n_merged",
    "n_abandoned",
    "n_open",
    "outcome",
    "ci_rerun_verified_drops",
    "ci_rerun_recheck_msgs",
]


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    """
    Write *rows* to a CSV file at *path*.

    Parameters
    ----------
    rows:
        List of topic-level metric dicts (keys must match :data:`_CSV_FIELDS`).
    path:
        Destination file path.
    """
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=_CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"  ✓ CSV written  → {path}")


def write_parquet(rows: list[dict[str, Any]], path: Path) -> None:
    """
    Write *rows* to a Parquet file at *path* using PyArrow.

    Parameters
    ----------
    rows:
        List of topic-level metric dicts.
    path:
        Destination file path.
    """
    if not rows:
        print("  ⚠ No rows to write — skipping Parquet output.")
        return

    schema = pa.schema([
        pa.field("topic_id", pa.string()),
        pa.field("n_changes", pa.int64()),
        pa.field("n_repos", pa.int64()),
        pa.field("n_branches", pa.int64()),
        pa.field("total_revisions", pa.int64()),
        pa.field("total_messages", pa.int64()),
        pa.field("n_reviewers", pa.int64()),
        pa.field("created_at", pa.string()),
        pa.field("last_updated_at", pa.string()),
        pa.field("time_to_completion_hours", pa.float64()),
        pa.field("n_merged", pa.int64()),
        pa.field("n_abandoned", pa.int64()),
        pa.field("n_open", pa.int64()),
        pa.field("outcome", pa.string()),
        pa.field("ci_rerun_verified_drops", pa.int64()),
        pa.field("ci_rerun_recheck_msgs", pa.int64()),
    ])

    columns: dict[str, list[Any]] = {field: [] for field in _CSV_FIELDS}
    for row in rows:
        for field in _CSV_FIELDS:
            columns[field].append(row.get(field))

    table = pa.table(columns, schema=schema)
    pq.write_table(table, str(path), compression="snappy")
    print(f"  ✓ Parquet written → {path}")


# ---------------------------------------------------------------------------
# Sanity-check / summary printing
# ---------------------------------------------------------------------------

def print_summary(
    all_changes: list[dict[str, Any]],
    topic_rows: list[dict[str, Any]],
    bot_accounts: set[int],
) -> None:
    """
    Print a human-readable summary of the dataset to stdout.

    Includes:
    - Total changes and topics
    - Distribution of n_changes per topic (min / median / max)
    - Outcome breakdown (percentage)
    - Topics with n_changes > :data:`LARGE_TOPIC_THRESHOLD`
    - Discovered Zuul/CI bot account IDs

    Parameters
    ----------
    all_changes:
        Full flat list of loaded Gerrit changes (for total count).
    topic_rows:
        Aggregated topic-level rows.
    bot_accounts:
        Discovered CI bot account IDs.
    """
    print("\n" + "=" * 70)
    print("Dataset Summary")
    print("=" * 70)
    print(f"  Total changes loaded : {len(all_changes):,}")
    print(f"  Total topics found   : {len(topic_rows):,}")

    if not topic_rows:
        print("  (No topics to summarise.)")
        return

    n_changes_list = [r["n_changes"] for r in topic_rows]
    median_val = statistics.median(n_changes_list)
    print(
        f"\n  n_changes per topic  : "
        f"min={min(n_changes_list)}, "
        f"median={median_val:.1f}, "
        f"max={max(n_changes_list)}"
    )

    # Outcome breakdown
    outcome_counts: dict[str, int] = {}
    for row in topic_rows:
        outcome_counts[row["outcome"]] = outcome_counts.get(row["outcome"], 0) + 1
    total_topics = len(topic_rows)
    print("\n  Outcome breakdown:")
    for outcome, count in sorted(outcome_counts.items()):
        pct = 100.0 * count / total_topics
        print(f"    {outcome:<15} {count:>6,}  ({pct:5.1f}%)")

    # Large topics
    large = [r for r in topic_rows if r["n_changes"] > LARGE_TOPIC_THRESHOLD]
    if large:
        print(f"\n  ⚠  Topics with n_changes > {LARGE_TOPIC_THRESHOLD} "
              f"(flag for manual inspection):")
        for row in sorted(large, key=lambda r: r["n_changes"], reverse=True):
            print(f"    {row['topic_id']!r:50s}  n_changes={row['n_changes']}")
    else:
        print(f"\n  ✓ No topics exceed the large-topic threshold of {LARGE_TOPIC_THRESHOLD}.")

    # Zuul bot accounts
    print("\n  Discovered CI/Zuul bot account_id(s):")
    if bot_accounts:
        for acct_id in sorted(bot_accounts):
            print(f"    {acct_id}")
    else:
        print("    (none detected — check CI_TAG_PREFIXES config)")

    print("=" * 70)


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------

def build_dataset() -> None:
    """
    Orchestrate the full topic-level aggregation pipeline:

    1. Load all raw changes from :data:`RAW_DATA_DIR`.
    2. Discover CI/Zuul bot accounts.
    3. Group changes by topic (drop null/empty topics).
    4. Aggregate metrics per topic.
    5. Write CSV and Parquet outputs.
    6. Print sanity-check summary.
    """
    now = datetime.now(tz=timezone.utc)

    # 1. Load
    all_changes = load_all_changes(RAW_DATA_DIR)

    # 2. Discover CI bots globally (before filtering)
    print("Discovering CI/Zuul bot accounts …")
    bot_accounts = discover_zuul_accounts(all_changes)
    print(f"  Found {len(bot_accounts)} bot account(s): {sorted(bot_accounts)}")

    # 3. Filter and group by topic
    print("Grouping changes by topic …")
    topic_map: dict[str, list[dict[str, Any]]] = {}
    skipped_no_topic = 0
    for change in all_changes:
        topic = (change.get("topic") or "").strip()
        if not topic:
            skipped_no_topic += 1
            continue
        topic_map.setdefault(topic, []).append(change)

    print(f"  Skipped {skipped_no_topic:,} changes with no topic.")
    print(f"  {len(topic_map):,} distinct topics found.")

    # 4. Aggregate
    print("Aggregating topic metrics …")
    topic_rows: list[dict[str, Any]] = []
    for topic, changes in sorted(topic_map.items()):
        row = aggregate_topic(topic, changes, bot_accounts, now)
        topic_rows.append(row)

    # Sort by n_changes descending for convenience
    topic_rows.sort(key=lambda r: r["n_changes"], reverse=True)

    # 5. Write outputs
    print("Writing outputs …")
    write_csv(topic_rows, OUTPUT_CSV)
    write_parquet(topic_rows, OUTPUT_PARQUET)

    # 6. Summary
    print_summary(all_changes, topic_rows, bot_accounts)


if __name__ == "__main__":
    build_dataset()
