def aggregate_topic(
    topic: str,
    changes: list[dict[str, Any]],
    bot_accounts: set[int],
    now: datetime,
) -> dict[str, Any]:
    """Compute all topic-level metrics for the given *changes*."""
    n_changes = len(changes)
    repos: set[str] = set()
    branches: set[str] = set()
    total_revisions = 0
    total_messages = 0
    reviewer_ids: set[int] = set()
    created_dts: list[datetime] = []
    updated_dts: list[datetime] = []
    submitted_dts: list[datetime] = []
    statuses: list[str] = []

    ci_rerun_verified_total = 0
    ci_rerun_recheck_total = 0

    # CI verification (FIXED)
    ci_successes_total = 0
    ci_failures_total = 0

    # Review-quality features
    total_code_review_plus2 = 0
    total_code_review_minus2 = 0
    first_review_delays: list[float] = []
    avg_review_delays: list[float] = []

    # Temporal
    active_days_list: list[int] = []

    # Patchset
    total_patchsets_all = 0
    max_files_changed_all: list[int] = []

    # Contributors
    code_authors_global: set[str] = set()
    people_involved_global: set[str] = set()
    people_per_change_counts: list[int] = []

    n_merged = n_abandoned = n_open = 0

    for change in changes:
        repos.add(change.get("project", "") or "")
        branches.add(change.get("branch", "") or "")

        revisions: dict[str, Any] = change.get("revisions") or {}
        total_revisions += len(revisions)

        messages: list[dict[str, Any]] = change.get("messages") or []
        total_messages += len(messages)

        reviewer_ids |= collect_reviewer_ids(change)

        dt_created = parse_gerrit_ts(change.get("created"))
        if dt_created:
            created_dts.append(dt_created)

        dt_updated = parse_gerrit_ts(change.get("updated"))
        if dt_updated:
            updated_dts.append(dt_updated)

        status = (change.get("status") or "").upper()
        statuses.append(status)

        if status == "MERGED":
            n_merged += 1
            dt_submitted = parse_gerrit_ts(change.get("submitted"))
            if dt_submitted:
                submitted_dts.append(dt_submitted)
        elif status == "ABANDONED":
            n_abandoned += 1
        else:
            n_open += 1

        # CI rerun heuristics (kept for backwards compatibility)
        ci_rerun_verified_total += count_verified_reruns(change, bot_accounts)
        ci_rerun_recheck_total += count_recheck_messages(change)

        # CI success / failure (FIXED — based on the sign of CI Verified votes)
        succ, fail = count_ci_verifications(change, bot_accounts)
        ci_successes_total += succ
        ci_failures_total += fail

        # Code review labels
        plus2, minus2 = extract_code_review_labels(change)
        total_code_review_plus2 += plus2
        total_code_review_minus2 += minus2

        # Review delays (bot-aware)
        first_delay, avg_delay = calculate_review_delays(change, bot_accounts)
        if first_delay is not None:
            first_review_delays.append(first_delay)
        if avg_delay is not None:
            avg_review_delays.append(avg_delay)

        # Active days
        active_days = get_active_days(change)
        if active_days is not None:
            active_days_list.append(active_days)

        # Patchset stats (renamed)
        total_ps, max_files = get_patchset_stats(change)
        total_patchsets_all += total_ps
        if max_files is not None:
            max_files_changed_all.append(max_files)

        # Contributor sets per change
        code_authors_change = get_code_authors(change)
        people_change = get_people_involved(change, bot_accounts)
        code_authors_global |= code_authors_change
        people_involved_global |= people_change
        people_per_change_counts.append(len(people_change))

    created_at = min(created_dts) if created_dts else None
    last_updated_at = max(updated_dts) if updated_dts else None

    # time_to_completion: only valid when ALL changes are merged
    time_to_completion_hours: float | None = None
    if n_merged == n_changes and submitted_dts and created_dts:
        time_to_completion_hours = hours_between(
            min(created_dts), max(submitted_dts)
        )

    outcome = classify_outcome(statuses, last_updated_at, now)

    # Robust aggregations
    avg_review_delay_hours = safe_mean(avg_review_delays)
    first_review_delay_hours = safe_mean(first_review_delays)
    avg_active_days = safe_mean(active_days_list)
    max_files_changed = safe_max(max_files_changed_all)
    avg_patchsets_per_change = (
        total_patchsets_all / n_changes if n_changes > 0 else None
    )

    # CI rate based on REAL success/failure counts (FIXED)
    ci_total_runs = ci_successes_total + ci_failures_total
    ci_failure_rate: float | None = (
        ci_failures_total / ci_total_runs if ci_total_runs > 0 else None
    )

    # Contributors
    authors_per_change_mean = safe_mean(people_per_change_counts)
    top_author_changes = get_top_author_changes(changes)

    return {
        # ORIGINAL FEATURES
        "topic_id": topic,
        "n_changes": n_changes,
        "n_repos": len(repos),
        "n_branches": len(branches),
        "total_revisions": total_revisions,
        "total_messages": total_messages,
        "n_reviewers": len(reviewer_ids),
        "created_at": created_at.isoformat() if created_at else None,
        "last_updated_at": last_updated_at.isoformat() if last_updated_at else None,
        "time_to_completion_hours": (
            round(time_to_completion_hours, 2)
            if time_to_completion_hours is not None
            else None
        ),
        "n_merged": n_merged,
        "n_abandoned": n_abandoned,
        "n_open": n_open,
        "outcome": outcome,
        "ci_rerun_verified_drops": ci_rerun_verified_total,
        "ci_rerun_recheck_msgs": ci_rerun_recheck_total,

        # Review-quality features
        "total_code_review_plus2": total_code_review_plus2,
        "total_code_review_minus2": total_code_review_minus2,
        "first_review_delay_hours": (
            round(first_review_delay_hours, 2)
            if first_review_delay_hours is not None else None
        ),
        "avg_review_delay_hours": (
            round(avg_review_delay_hours, 2)
            if avg_review_delay_hours is not None else None
        ),

        # Temporal features
        "last_activity_gap_days": (
            (now - last_updated_at).days if last_updated_at else None
        ),
        "avg_active_days": (
            round(avg_active_days, 2) if avg_active_days is not None else None
        ),

        # Patchset features (renamed)
        "total_patchsets": total_patchsets_all,
        "avg_patchsets_per_change": (
            round(avg_patchsets_per_change, 2)
            if avg_patchsets_per_change is not None else None
        ),
        "max_files_changed": max_files_changed,

        # CI features (FIXED — based on real successes/failures)
        "ci_runs": ci_total_runs,
        "ci_successes": ci_successes_total,
        "ci_failures": ci_failures_total,
        "ci_failure_rate": (
            round(ci_failure_rate, 3) if ci_failure_rate is not None else None
        ),
        # Retries: human (recheck msgs) + auto-rerun (verified drops)
        "ci_retries": ci_rerun_verified_total + ci_rerun_recheck_total,

        # Contributor features (clarified semantics)
        # Broad: every distinct human involved (owner + uploaders + commenters)
        "people_involved_count": len(people_involved_global),
        # Strict: only owners + uploaders (real code authors)
        "code_authors_count": len(code_authors_global),
        # Backwards-compat alias (= people_involved_count)
        "author_count": len(people_involved_global),
        "authors_per_change": (
            round(authors_per_change_mean, 2)
            if authors_per_change_mean is not None else None
        ),
        "top_author_changes": top_author_changes,
    }


