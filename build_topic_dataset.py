#: Root directory that contains the raw JSON collected by collect_changes.py
RAW_DATA_DIR: Path = Path("raw_data")

#: Output CSV file path
OUTPUT_CSV: Path = Path("topics_dataset.csv")

#: Output Parquet file path
OUTPUT_PARQUET: Path = Path("topics_dataset.parquet")

#: Topics whose n_changes exceeds this threshold is flagged for manual review.
LARGE_TOPIC_THRESHOLD: int = 50

#: An open change with no activity for more than this many days is "stale".
STALE_OPEN_DAYS: int = 90

#: Prefix strings used in Gerrit label vote tag fields that identify CI bots.
CI_TAG_PREFIXES: tuple[str, ...] = ("autogenerated:zuul",)

#: Message-tag prefixes used by Zuul / CI to post automated comments.
#: Used to exclude bot messages from review-delay calculations.
CI_MESSAGE_TAG_PREFIXES: tuple[str, ...] = (
    "autogenerated:zuul",
    "autogenerated:ci",
)

#: Substrings (case-insensitive) used as a fallback to detect bot usernames
#: in message authors when no ``tag`` or ``_account_id`` match is available.
BOT_USERNAME_HINTS: tuple[str, ...] = ("zuul", "jenkins", "bot", "ci")


# ---------------------------------------------------------------------------
# Datetime helpers
# ---------------------------------------------------------------------------

_GERRIT_TS_FORMATS: list[str] = [
    "%Y-%m-%d %H:%M:%S.%f000",   # with microseconds (Gerrit default)
    "%Y-%m-%d %H:%M:%S.%f",
    "%Y-%m-%d %H:%M:%S",
]


def parse_gerrit_ts(ts: str | None) -> datetime | None:
    """
    Parse a Gerrit timestamp string into an aware UTC :class:`datetime`.
    """
    if not ts:
        return None
    ts_norm = re.sub(r"(\.\d{6})\d+", r"\1", ts)
    for fmt in _GERRIT_TS_FORMATS:
        try:
            dt = datetime.strptime(ts_norm, fmt)
            return dt.replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def hours_between(start: datetime | None, end: datetime | None) -> float | None:
    """Return elapsed hours between *start* and *end*, or ``None`` if missing."""
    if start is None or end is None:
        return None
    return (end - start).total_seconds() / 3600.0


def safe_mean(values: Iterable[float]) -> float | None:
    """
    Return the arithmetic mean of *values*, or ``None`` if the iterable is empty.

    Wraps :func:`statistics.mean` to avoid ``StatisticsError`` on empty input.
    """
    seq = [v for v in values if v is not None]
    if not seq:
        return None
    return statistics.mean(seq)


def safe_max(values: Iterable[float]) -> float | None:
    """Return ``max(values)`` or ``None`` if the iterable is empty."""
    seq = [v for v in values if v is not None]
    if not seq:
        return None
    return max(seq)


